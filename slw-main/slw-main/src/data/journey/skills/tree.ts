// Дерево навыков БС — 4 общих базовых + 47 архетипных = 51 навык.
//
// Архетипы соответствуют четырём «полным образам» БС из соционики:
// Целитель, Эстет, Мастер Наслаждения, Хранитель Очага.
//
// Общие базовые — четыре сквозных навыка (body-listening,
// needs-awareness, timely-care, details), которые проходят через все
// четыре архетипа: вход (слушать тело) → понимание (осознавать
// потребности) → выход (своевременно заботиться) + базовое качество
// тонкости (внимание к мелким деталям). В UI отображаются в каждой
// ветке с пометкой «общий», в среднем по архетипу учитываются как доп.
// слагаемые (см. calcArchetypeAvg).
//
// id навыка — короткий латинский ключ. Используется как имя файла md
// (ну или как ключ в один md-файле через парсер) и как id анкеты.
//
// order внутри архетипа — порядок отображения в дереве (от базовых
// к продвинутым).
//
// История изменений:
// v1: 33 навыка (стартовая разбивка).
// v2: ревизия структуры — слияния и расширение:
//   - scan → interoception (сканирование как метод соматического осознания)
//   - relax → balance (глубокое расслабление как часть баланса напр./расслабл.)
//   - aging → pain (старение как часть принятия телесных изменений)
//   - env-quality → quality (различение качества среды — частный случай)
//   - env-design → ergonomics (программирование среды как часть настройки)
//   - load → pause (управление нагрузкой через паузы)
//   - library → pleasure (библиотека приятных ощущений как часть наслаждения)
//   + 21 новый навык (см. список ниже).
//   Итого 33 - 7 + 21 = 47.
//   Миграция id для старых результатов анкет — в JourneyView.jsx
//   (SKILL_ID_MIGRATION + migrateSkills).
// v3: 3 базовых навыка (signals / interoception / honesty) выделены
//   из healer в общие — они входят в средний по каждому архетипу.
//   Эти же 3 анкеты включены в L0-чат как первая оценка БС.
//   Id остались прежними, миграция данных не нужна.
// v4: общие базовые перепроектированы. signals / interoception /
//   honesty возвращены в healer как обычные навыки архетипа (свои
//   архетипные id и анкеты сохраняются). На их место в COMMON_BASE
//   введены 4 сквозных навыка верхнего уровня:
//   - body-listening — слушать тело (вход)
//   - needs-awareness — осознавать потребности (понимание)
//   - timely-care — своевременно заботиться (выход)
//   - details — внимание к мелким деталям (базовое качество тонкости)
//   Полное описание см. в `Si/Навыки БС — Универсальные.md`.
//   В L0-чате три старые анкеты SURV-100/101/102 заменены на четыре
//   новые. CONTENT_VERSION бампнут, L0 у юзеров перезапустится.
//   Их данные по signals/interoception/honesty (прошлые анкеты)
//   сохраняются — id остался прежним, навыки переехали из COMMON_BASE
//   в SKILL_TREE.healer.

// Узел дерева навыков: листовая запись для UI. Si-уровень — плоские
// списки внутри архетипных веток (без вложенных детей). Другие
// аспекты (Ne/Ni/Te/Ti/Fi/Se/Fe) повторяют ту же форму, у некоторых
// (Si/Ne/Ni/Fi/Te/Se/Fe) общие базовые помечены флагом `isCommon`.
